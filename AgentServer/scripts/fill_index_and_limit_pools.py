col = db['index_daily']
for code, d in idx_data.items():
    ops = []
    for i, t in enumerate(d['time']):
        td = int(t.replace('-', ''))
        doc = {
            'ts_code': code, 'trade_date': td,
            'open': d['open'][i], 'close': d['close'][i],
            'high': d['high'][i], 'low': d['low'][i],
            'pct_chg': d['pct_chg'][i],
            'vol': int(d['volume'][i]), 'amount': d['amt'][i],
            'pre_close': d['pre_close'][i],
        }
        ops.append(UpdateOne({'ts_code': code, 'trade_date': td}, {'$set': doc}, upsert=True))
    if ops:
        r = col.bulk_write(ops)
        print(f'{code}: 插入{r.upserted_count}条, 更新{r.modified_count}条')

# ===== 2. 涨跌停池(从is_limit_up/is_limit_down反推) =====
sd_dates = sorted(db['stock_daily_ak_full'].distinct('trade_date'))
ll_dates = set(db['limit_list'].distinct('trade_date'))
lp_dates = set(db['limit_pool_down'].distinct('trade_date'))

missing_ll = [d for d in sd_dates if d not in ll_dates and d >= 20260501]
missing_lp = [d for d in sd_dates if d not in lp_dates and d >= 20260501]

print(f'\n涨跌停池缺失: limit_list={len(missing_ll)}天, limit_pool_down={len(missing_lp)}天')

# 补limit_list
for td in missing_ll:
    docs = list(db['stock_daily_ak_full'].find(
        {'trade_date': td, 'is_limit_up': 1},
        {'ts_code': 1, 'pct_chg': 1, 'close': 1, 'open': 1, 'high': 1, 'low': 1, 'vol': 1, 'amount': 1, 'pre_close': 1, 'turnover_rate': 1, 'circ_mv': 1, '_id': 0}
    ))
    ops = []
    for doc in docs:
        doc['trade_date'] = td
        doc['data_source'] = 'backfill_from_daily'
        ops.append(UpdateOne({'ts_code': doc['ts_code'], 'trade_date': td}, {'$set': doc}, upsert=True))
    if ops:
        r = db['limit_list'].bulk_write(ops)
        print(f'  limit_list {td}: {r.upserted_count}新+{r.modified_count}改')

# 补limit_pool_down
